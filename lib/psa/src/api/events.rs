//! Immutable transcript events. Sequence numbers are local to an agent lineage.

use crate::api::{AgentId, AgentResult, AgentState, ToolId};
use llm_api::api::{
    ContentBlock, HistoryItem, HistoryItemMetadata, Outcome, ProviderFields, Reasoning,
    RequestConfig, TextBlock, ToolDefinition as ApiToolDefinition, Usage,
};
use llm_api::providers::ModelConfig;
use serde::{Deserialize, Serialize};
use std::time::Duration;
use time::OffsetDateTime;

/// Sequence number within an agent's event lineage.
#[derive(
    Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash, Default, Serialize, Deserialize,
)]
pub struct EventId(pub u64);

/// An immutable, committed transcript event.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct Event {
    /// Sequence number in the agent lineage.
    pub id: EventId,
    /// Physical owner, which may be an ancestor of the requested agent.
    pub source_agent_id: AgentId,
    /// Event time in RFC 3339 format.
    #[serde(with = "time::serde::rfc3339")]
    pub timestamp: OffsetDateTime,
    /// Transcript event payload.
    pub kind: EventType,
}

/// Payload of a committed or provisional transcript event.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub enum EventType {
    /// Records a change in agent execution state.
    StatusChange(StatusChange),
    /// Updates the model configuration used by subsequent context.
    Model(ModelConfig),
    /// Starts a new model-facing context.
    NewContext,
    /// Records a message in the conversation.
    Message(Message),
    /// Records model reasoning and replay metadata.
    Thinking(Thinking),
    /// Records a provider-native history item.
    ProviderItem(HistoryItem),
    /// Publishes a native tool's model-facing definition.
    ToolDefinition(ToolDefinition),
    /// Records a requested tool invocation.
    ToolCall(ToolCall),
    /// Records the result of a tool invocation.
    ToolResult(ToolResult),
    /// Records a durable agent result artifact, separate from ordinary messages.
    Result(AgentResult),
    /// Appends a compacted summary; pair with NewContext to replace older history.
    Compaction(Compaction),
    /// Records a harness diagnostic.
    Log(Log),
    /// Records a slash command and how it ended, after it finished.
    Command(CommandRecord),
    /// Begins the recorded result of an inference, not the request itself.
    InferenceResultStart(InferenceResultStart),
    /// Ends a recorded inference result with outcome and usage.
    InferenceResultEnd(InferenceResultEnd),
    /// Records a decision-model call. Not part of the model's context.
    DecisionCall(crate::api::DecisionCall),
}

/// Origin or role of a transcript message.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
pub enum MessageType {
    /// An attributed message from another agent.
    Subagent,
    /// A message supplied by a human or client.
    Human,
    /// An assistant message generated by the model.
    Agent,
    /// A message supplied by the agent harness.
    Harness,
    /// A system instruction message.
    System,
}

/// One agent-to-agent message. The same link is recorded on both sides: on the
/// received [`MessageType::Subagent`] message, and on the result of the
/// `send_message` or `create_agent` call that sent it, so clients can jump
/// between them by `request_id`.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct AgentMessageLink {
    /// Server-assigned request that delivered the message.
    pub request_id: String,
    /// Sending agent.
    pub sender: AgentId,
    /// Sending agent's name captured at submission.
    pub sender_name: String,
    /// Receiving agent.
    pub recipient: AgentId,
    /// Receiving agent's name captured at submission.
    pub recipient_name: String,
}

/// Conversation content with its origin and replay metadata.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct Message {
    /// Link to the sending agent; set on, and only on, subagent messages.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub source: Option<AgentMessageLink>,
    /// Short display description, primarily for system instructions.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub description: Option<String>,
    /// Origin or role of this message.
    pub message_type: MessageType,
    /// Ordered message content blocks.
    pub content: Vec<ContentBlock>,
    /// Provider replay metadata associated with this message.
    pub metadata: HistoryItemMetadata,
}

impl Message {
    /// Creates a single plain-text message without sender attribution or replay metadata.
    pub fn text(message_type: MessageType, contents: impl Into<String>) -> Self {
        Self {
            source: None,
            description: None,
            message_type,
            content: vec![ContentBlock::Text(TextBlock {
                text: contents.into(),
                annotations: Vec::new(),
            })],
            metadata: HistoryItemMetadata::default(),
        }
    }

    /// Creates a system instruction with a short transcript description.
    pub fn system(contents: impl Into<String>, description: impl Into<String>) -> Self {
        let mut message = Self::text(MessageType::System, contents);
        message.description = Some(description.into());
        message
    }
}

#[cfg(test)]
mod message_tests {
    use super::*;

    #[test]
    fn system_description_is_optional_and_round_trips() {
        let plain = serde_json::to_value(Message::text(MessageType::System, "prompt")).unwrap();
        assert!(plain.get("description").is_none());
        let decoded: Message = serde_json::from_value(plain).unwrap();
        assert_eq!(decoded.description, None);

        let described = Message::system("prompt", "Base instructions");
        let json = serde_json::to_value(described).unwrap();
        assert_eq!(json["description"], "Base instructions");
        let decoded: Message = serde_json::from_value(json).unwrap();
        assert_eq!(decoded.description.as_deref(), Some("Base instructions"));
    }
}

/// Model reasoning and its associated replay metadata.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct Thinking {
    /// Reasoning content, including any opaque provider state.
    pub contents: Reasoning,
    /// Provider replay metadata for this reasoning item.
    pub metadata: HistoryItemMetadata,
}

/// A native tool identifier paired with its model-facing schema.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct ToolDefinition {
    /// Native tool implementation identifier.
    pub id: ToolId,
    /// Model-facing name, description, and argument schema.
    pub definition: ApiToolDefinition,
}

/// Identifier correlating a tool invocation with its result.
pub type ToolCallId = String;

/// A model-requested tool invocation.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct ToolCall {
    /// Identifier used to match the eventual tool result.
    pub call_id: ToolCallId,
    /// Name of the tool requested by the model.
    pub tool_name: String,
    /// Preserve unparsed arguments, including malformed JSON.
    pub arguments: String,
    /// Provider replay metadata associated with the call.
    pub metadata: HistoryItemMetadata,
}

/// Content and error status returned for a tool invocation.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct ToolResult {
    /// Identifier of the corresponding tool call.
    pub call_id: ToolCallId,
    /// Ordered tool output content blocks.
    pub content: Vec<ContentBlock>,
    /// Whether the tool execution reported an error.
    pub error: bool,
    /// Provider replay metadata associated with the result.
    pub metadata: HistoryItemMetadata,
    /// Agent message this call delivered, for clients linking a sent message
    /// to its receipt. Never sent to the model.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub delivery: Option<AgentMessageLink>,
}

/// Portable text or a provider-native summary of compacted context.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub enum CompactionSummary {
    /// A text summary used to replace previous model-facing context.
    Text(String),
    /// A provider-native history item representing the compacted context.
    ProviderItem(HistoryItem),
}

/// A context compaction result and its inference usage.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct Compaction {
    /// Summary replacing the earlier model-facing context.
    pub summary: CompactionSummary,
    /// Token usage reported for the compaction operation.
    pub usage: Usage,
}

/// A persisted change to an agent's execution state.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct StatusChange {
    /// State entered by the agent.
    pub new_status: AgentState,
    /// Optional explanation for the transition.
    pub reason: Option<String>,
}

/// A diagnostic message emitted by the harness.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct Log {
    /// Whether this diagnostic represents an error.
    pub error: bool,
    /// Diagnostic text.
    pub message: String,
}

/// A slash command as the user typed it, recorded once it finished. Server
/// commands are recorded by the worker that ran them; client-only commands are
/// recorded through [`crate::api::AgentRequest::RecordCommand`].
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct CommandRecord {
    /// Command name without the leading slash, such as `compact`.
    pub name: String,
    /// Everything after the name, trimmed; empty when there were no arguments.
    pub args: String,
    /// How the command ended.
    pub outcome: crate::api::CommandOutcome,
    /// Text the command reported, such as a failure reason.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub output: Option<String>,
}

impl CommandRecord {
    /// The record of a typed agent command that finished with `result`.
    pub fn new(command: &crate::api::AgentCommand, result: crate::api::CommandResult) -> Self {
        Self {
            name: command.name().into(),
            args: command.args(),
            outcome: result.outcome,
            output: result.output,
        }
    }

    /// The command as typed: `/name`, followed by its arguments when present.
    pub fn command_line(&self) -> String {
        if self.args.is_empty() {
            format!("/{}", self.name)
        } else {
            format!("/{} {}", self.name, self.args)
        }
    }
}

/// Identifier correlating the start and end of a recorded inference result.
pub type InferenceId = u64;

/// Configuration attribution that precedes a recorded inference result.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct InferenceResultStart {
    /// Identifier shared with the corresponding inference-result end.
    pub id: InferenceId,
    /// Snapshot of the model that produced this result, not a request-start event.
    pub model_config: ModelConfig,
    /// Request options used for this inference.
    pub request_config: RequestConfig,
}

/// Terminal outcome and accounting for a recorded inference result.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct InferenceResultEnd {
    /// Identifier shared with the corresponding inference-result start.
    pub id: InferenceId,
    /// Must be terminal. Preserves incomplete/failed/cancelled distinctions.
    pub outcome: Outcome,
    /// Token usage reported by the provider.
    pub usage: Usage,
    /// Elapsed inference time, including response collection.
    pub request_time: Duration,
    /// Provider response identifier, when supplied.
    pub response_id: Option<String>,
    /// Additional response-level metadata supplied by the provider.
    pub provider_metadata: ProviderFields,
}
